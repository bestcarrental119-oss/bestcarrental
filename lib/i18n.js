export function normalizeLocale(locale) {
  const clean = String(locale ?? 'en').trim().replace('_', '-');
  const lower = clean.toLowerCase();
  if (lower === 'zh') return 'zh-CN';
  if (lower === 'zh-cn' || lower === 'zh-hans') return 'zh-CN';
  if (lower === 'zh-tw' || lower === 'zh-hant') return 'zh-TW';

  const exact = LOCALES.find(item => item.code.toLowerCase() === lower);
  if (exact) return exact.code;

  const base = lower.split('-')[0];
  const baseLocale = LOCALES.find(item => item.code.toLowerCase() === base);
  return baseLocale?.code ?? 'en';
}

